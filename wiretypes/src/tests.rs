mod shapes {
    use std::collections::HashMap;

    use serde::{Deserialize, Serialize};

    use crate::wire;

    #[wire]
    pub const LIMIT: u16 = 3;

    #[wire]
    #[derive(Serialize)]
    pub struct Base {
        pub name: Box<str>,
        #[serde(rename = "semanticId")]
        pub semantic_id: String,
        #[serde(rename = "rawCites", skip_serializing_if = "Option::is_none")]
        pub raw_cites: Option<u32>,
        pub screened: Option<usize>,
    }

    /// A row of a table.
    #[wire]
    #[derive(Serialize)]
    pub struct Row {
        #[serde(flatten)]
        pub base: Base,
        pub values: HashMap<String, f64>,
        pub span: (u16, u16),
        pub groups: Groups,
        pub tree: super::nested::TreeNode,
    }

    #[wire]
    #[derive(Serialize)]
    pub struct Groups {
        #[serde(rename = "paper-fields")]
        pub paper_fields: Vec<Base>,
    }

    #[wire]
    #[derive(Deserialize)]
    #[serde(tag = "kind", rename_all = "snake_case")]
    pub enum Payload {
        Claim { work: Option<u64> },
        Revoke,
    }

    #[wire]
    #[derive(Serialize)]
    #[serde(rename_all = "snake_case")]
    pub enum Reason {
        MissingId,
        NotInDataset,
    }
}

mod limits {
    use std::sync::LazyLock;

    use serde::Serialize;

    use crate::wire;

    /// Rows one page holds.
    #[wire]
    pub const PAGE: usize = 25;
    #[wire]
    const ROOT: &str = "/tmp/it's";
    #[wire]
    pub const BANDS: [(f64, &str); 2] = [(0.2, "top"), (0.01, "rare")];
    #[wire]
    pub const ONE: &[u8] = &[7];
    #[wire]
    pub const SCREEN: Screen = Screen {
        min: 1,
        max_rows: 20,
        span: (1951, 2026),
        kinds: &["article"],
    };
    #[wire]
    pub static ON: bool = true;
    #[wire]
    pub static BUILT: LazyLock<Screen> = LazyLock::new(|| Screen { min: 2, ..SCREEN });

    #[wire]
    #[derive(Serialize)]
    pub struct Screen {
        pub min: u8,
        #[serde(rename = "max-rows")]
        pub max_rows: u32,
        pub span: (u16, u16),
        pub kinds: &'static [&'static str],
    }
}

mod nested {
    use std::collections::HashMap;

    use serde::Serialize;

    use crate::wire;

    #[wire]
    #[derive(Serialize, Default)]
    pub struct NodeGen<T: Default> {
        #[serde(rename = "topSourceId")]
        pub top: T,
    }

    #[wire]
    pub type NodeJson = NodeGen<Option<u64>>;

    #[wire]
    #[derive(Serialize)]
    pub struct TreeNode {
        #[serde(flatten)]
        pub node: NodeJson,
        pub children: Box<Children>,
    }

    #[wire]
    #[derive(Serialize)]
    #[serde(untagged)]
    pub enum Children {
        Leaves(HashMap<u32, NodeJson>),
        Nodes(HashMap<u32, TreeNode>),
    }
}

