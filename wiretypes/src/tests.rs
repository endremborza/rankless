fn model() -> Model {
    Model::collect(
        inventory::iter::<WireType>(),
        inventory::iter::<WireConst>(),
    )
    .unwrap()
}

#[test]
fn typescript_spells_each_module_with_its_imports() {
    let files = ts::render(&model(), "make types").unwrap();
    assert_eq!(files["wiretypes/tests/shapes.ts"], TS_SHAPES);
    assert_eq!(files["wiretypes/tests/nested.ts"], TS_NESTED);
}

#[test]
fn values_become_literals_ahead_of_the_types() {
    let model = model();
    let ts = ts::render(&model, "make types").unwrap();
    assert_eq!(ts["wiretypes/tests/limits.ts"], TS_LIMITS);
    let py = python::render(&model, PythonStyle::TypedDict, "make types").unwrap();
    assert_eq!(py["wiretypes/tests/limits.py"], PY_LIMITS);
}

#[test]
fn python_hoists_variants_and_spells_odd_keys_functionally() {
    let files = python::render(&model(), PythonStyle::TypedDict, "make types").unwrap();
    assert_eq!(files["wiretypes/tests/shapes.py"], PY_SHAPES);
    let packages: Vec<&str> = files
        .keys()
        .map(String::as_str)
        .filter(|p| p.ends_with("__init__.py"))
        .collect();
    assert_eq!(
        packages,
        [
            "__init__.py",
            "wiretypes/__init__.py",
            "wiretypes/tests/__init__.py"
        ]
    );
}

