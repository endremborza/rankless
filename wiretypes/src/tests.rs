#[test]
fn check_reports_drift_and_write_removes_stale_files() {
    let dir = std::env::temp_dir().join(format!("wiretypes-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    let render = |files: &[(&str, &str)]| -> BTreeMap<String, BTreeMap<String, String>> {
        let files = files
            .iter()
            .map(|(p, c)| (p.to_string(), c.to_string()))
            .collect();
        [("out".to_string(), files)].into()
    };
    let header = output::header("m", "make types");
    let (a, b) = (format!("// {header}\na"), format!("// {header}\nb"));
    let hand_written = dir.join("out/keep.ts");

    output::write(&dir, &render(&[("a.ts", &a), ("sub/b.ts", &b)])).unwrap();
    std::fs::write(&hand_written, "export {};\n").unwrap();
    output::check(
        &dir,
        &render(&[("a.ts", &a), ("sub/b.ts", &b)]),
        "make types",
    )
    .unwrap();

    let next = render(&[("a.ts", &b)]);
    let drift = output::check(&dir, &next, "make types")
        .unwrap_err()
        .to_string();
    assert!(
        drift.contains("differs: out/a.ts") && drift.contains("stale: out/sub/b.ts"),
        "{drift}"
    );

    output::write(&dir, &next).unwrap();
    output::check(&dir, &next, "make types").unwrap();
    assert!(hand_written.exists());
    std::fs::remove_dir_all(&dir).unwrap();
}

