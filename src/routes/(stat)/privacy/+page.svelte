			own profiles, using their ORCID identifiers for this purpose.
		</p>
		<p>
			By clicking the “Register/Log In” button on the Rankless page, the user is redirected to the
			ORCID login interface.
		</p>
		<p>
			After logging in to ORCID or creating a new account, the user is directed to a page that is
			still within the ORCID platform.
		</p>
		<p>
			Here, the user can grant Rankless access to their ORCID ID; once access is granted, the user
			is redirected back to the Rankless site, where they can use the platform while logged in.
		</p>
